create or replace view "public"."v_btx_summary" as  WITH latest AS (
         SELECT DISTINCT ON (b_1.submission_id) b_1.submission_id,
            b_1.created_at,
            b_1.type,
            b_1.control_no,
            b_1.wave_no,
            b_1.submitted_by
           FROM btx b_1
          WHERE (b_1.submission_id IS NOT NULL)
          ORDER BY b_1.submission_id, b_1.created_at DESC
        )
 SELECT l.created_at,
    COALESCE((to_jsonb(p.*) ->> 'username'::text), (to_jsonb(p.*) ->> 'full_name'::text), NULLIF(TRIM(BOTH FROM concat_ws(' '::text, (to_jsonb(p.*) ->> 'first_name'::text), (to_jsonb(p.*) ->> 'last_name'::text))), ''::text), (to_jsonb(p.*) ->> 'email'::text), (l.submitted_by)::text) AS user_display,
    l.type,
    l.control_no,
    l.wave_no,
    COALESCE(sum(b.pallets), (0)::bigint) AS pallets,
    COALESCE(sum(b.cartons), (0)::bigint) AS cartons,
    l.submission_id
   FROM ((latest l
     JOIN btx b ON ((b.submission_id = l.submission_id)))
     LEFT JOIN profiles p ON ((p.id = l.submitted_by)))
  GROUP BY l.created_at, l.type, l.control_no, l.wave_no, l.submitted_by, p.id, l.submission_id;


