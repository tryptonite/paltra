create or replace view "public"."v_dimensions_summary" as  WITH ranked AS (
         SELECT d.id,
            d.created_at,
            d.control_no,
            d.length_in,
            d.width_in,
            d.height_in,
            d.qty,
            d.submitted_by,
            d.updated_at,
            d.control_no_norm,
            d.volume_in3,
            d.ship_via,
            d.skids,
            d.cartons,
            d.wave_no,
            row_number() OVER (PARTITION BY d.control_no ORDER BY d.created_at DESC, d.id DESC) AS rn
           FROM dimensions d
        )
 SELECT r.created_at,
    COALESCE((to_jsonb(p.*) ->> 'username'::text), (to_jsonb(p.*) ->> 'full_name'::text), NULLIF(TRIM(BOTH FROM concat_ws(' '::text, (to_jsonb(p.*) ->> 'first_name'::text), (to_jsonb(p.*) ->> 'last_name'::text))), ''::text), (to_jsonb(p.*) ->> 'email'::text), (r.submitted_by)::text) AS user_display,
    r.control_no,
    r.wave_no,
    r.ship_via,
    COALESCE(r.skids, 0) AS skids,
    COALESCE(r.cartons, 0) AS cartons
   FROM (ranked r
     LEFT JOIN profiles p ON ((p.id = r.submitted_by)))
  WHERE (r.rn = 1);


