CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), 'general')
  on conflict (id) do nothing;
  return new;
end; $function$
;

CREATE OR REPLACE FUNCTION public.set_submitted_by_name()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  v_name text;
begin
  if new.submitted_by is null then
    return new;
  end if;

  select coalesce(
           p.full_name,
           au.raw_user_meta_data->>'full_name',
           au.raw_user_meta_data->>'username',
           split_part(au.email, '@', 1)
         )
    into v_name
  from auth.users au
  left join public.profiles p on p.id = au.id
  where au.id = new.submitted_by;

  new.submitted_by_name := v_name;
  return new;
end
$function$
;

